/**
 * Turns the markdown sources in src/content/src into a generated TypeScript
 * module (src/content/lessons.generated.ts). Run with: node scripts/build-content.mjs
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const SRC_DIR = "src/content/src";
const OUT = "src/content/lessons.generated.ts";

const files = readdirSync(SRC_DIR).filter((f) => f.endsWith(".md")).sort();
const lessons = [];

for (const file of files) {
  const text = readFileSync(join(SRC_DIR, file), "utf8");
  const parts = text.split(/^@LESSON /m).filter((p) => p.trim().length);
  for (const part of parts) {
    const newline = part.indexOf("\n");
    const header = part.slice(0, newline).trim();
    const body = part
      .slice(newline + 1)
      .replace(/\s+$/, "")
      .replace(/\n{3,}/g, "\n\n");
    const fields = {};
    for (const chunk of header.split("|")) {
      const idx = chunk.indexOf("=");
      if (idx > 0) fields[chunk.slice(0, idx).trim()] = chunk.slice(idx + 1).trim();
    }
    if (!fields.slug || !fields.title) throw new Error(`Bad @LESSON header in ${file}: ${header}`);
    lessons.push({
      slug: fields.slug,
      title: fields.title,
      module: fields.module || "COBOL Basics",
      order: Number(fields.order || 0),
      summary: fields.summary || "",
      body,
    });
  }
}

lessons.sort((a, b) => a.order - b.order);

const banner = `// AUTO-GENERATED by scripts/build-content.mjs - do not edit by hand.
// Source of truth: src/content/src/*.md
`;

const out = `${banner}
export interface GeneratedLesson {
  slug: string;
  title: string;
  module: string;
  order: number;
  summary: string;
  body: string;
}

export const generatedLessons: GeneratedLesson[] = ${JSON.stringify(lessons, null, 2)};
`;

mkdirSync("src/content", { recursive: true });
writeFileSync(OUT, out, "utf8");
console.log(`Wrote ${lessons.length} lessons to ${OUT}`);
